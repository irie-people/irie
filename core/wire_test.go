package core

import (
	"bytes"
	"flag"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "write wire.go from internal/ipc")

// serverOnly are internal/ipc's exported names that only the core uses, to
// serve: a client never needs them.
var serverOnly = map[string]bool{"Handler": true, "Listen": true, "Serve": true}

// wire is what wire.go must hold: an alias for every exported type and
// constant of internal/ipc, in the order its files declare them.
func wire(t *testing.T) []byte {
	t.Helper()
	var types, consts []string
	for _, file := range parse(t, filepath.Join("..", "internal", "ipc")) {
		for _, d := range file.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, s := range g.Specs {
				switch s := s.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() && !serverOnly[s.Name.Name] {
						types = append(types, s.Name.Name)
					}
				case *ast.ValueSpec:
					if g.Tok != token.CONST {
						continue
					}
					for _, n := range s.Names {
						if n.IsExported() {
							consts = append(consts, n.Name)
						}
					}
				}
			}
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by `go generate ./core` from internal/ipc; DO NOT EDIT.\n\n")
	b.WriteString("package core\n\nimport \"github.com/irie-people/irie/internal/ipc\"\n\n")
	b.WriteString("// The wire's types: the requests and replies, every op's args and result,\n")
	b.WriteString("// the frames of a subscription and the rows they carry (DESIGN §2.4).\n")
	b.WriteString("type (\n")
	for _, n := range types {
		b.WriteString("\t" + n + " = ipc." + n + "\n")
	}
	b.WriteString(")\n\n")
	b.WriteString("// The wire's constants: the API version, the op and frame names, the\n")
	b.WriteString("// states, the error codes and the other values its fields take.\n")
	b.WriteString("const (\n")
	for _, n := range consts {
		b.WriteString("\t" + n + " = ipc." + n + "\n")
	}
	b.WriteString(")\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// The contract can't fall behind the wire: a type or constant added to
// internal/ipc fails this test until `go generate ./core` adds it here.
func TestWireCoversTheProtocol(t *testing.T) {
	want := wire(t)
	if *update {
		if err := os.WriteFile("wire.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("wire.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("core/wire.go does not match internal/ipc: run `go generate ./core`")
	}
}

// Every function a client needs is here too.
func TestTheClientFunctionsAreHere(t *testing.T) {
	have := map[string]bool{}
	for _, f := range parse(t, ".") {
		for _, d := range f.Decls {
			if fn, ok := d.(*ast.FuncDecl); ok && fn.Recv == nil {
				have[fn.Name.Name] = true
			}
		}
	}
	for _, f := range parse(t, filepath.Join("..", "internal", "ipc")) {
		for _, d := range f.Decls {
			fn, ok := d.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || !fn.Name.IsExported() || serverOnly[fn.Name.Name] {
				continue
			}
			if !have[fn.Name.Name] {
				t.Errorf("internal/ipc.%s has no counterpart in core: add one to core/client.go, or list it in serverOnly", fn.Name.Name)
			}
		}
	}
}

// parse parses the Go files of dir but its tests, in the order of their
// names.
func parse(t *testing.T, dir string) []*ast.File {
	t.Helper()
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		t.Fatal(err)
	}
	sort.Strings(names)
	var out []*ast.File
	fset := token.NewFileSet()
	for _, n := range names {
		if strings.HasSuffix(n, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, n, nil, parser.SkipObjectResolution)
		if err != nil {
			t.Fatal(err)
		}
		out = append(out, f)
	}
	return out
}
