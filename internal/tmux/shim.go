package tmux

import (
	"bytes"
	"io"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// ShimMark is the line that marks the tmux a session's agent finds first on
// its PATH: a script that runs `irie team-tmux` (internal/team), which then
// runs tmux. It is not tmux, and it costs a whole irie on every call. An
// `irie up` run from an agent's shell used to hand the agent's PATH to the
// new core, since tmux starts a pane with the PATH of the client that asks.
// The core then ran every tmux command through that shim, whose own tmux was
// the shim of the session before, and so on: five deep on 2026-11-01, about
// 50 ms a command instead of under 10, with the core's lock held throughout.
// So Find never takes a shim, and a PATH with one is cleaned (CleanPath)
// before it reaches a core.
const ShimMark = "# Generated by Irie: Claude Code's agent teams reach Irie's team server"

// IsShim reports whether the file at p is one of Irie's tmux shims.
func IsShim(p string) bool {
	f, err := os.Open(p)
	if err != nil {
		return false
	}
	defer f.Close()
	head := make([]byte, 512)
	n, _ := io.ReadFull(f, head)
	return bytes.Contains(head[:n], []byte(ShimMark))
}

// CleanPath is a PATH list without the dirs whose tmux is one of Irie's
// shims. Every other dir stays, in its place.
func CleanPath(path string) string {
	dirs := filepath.SplitList(path)
	keep := dirs[:0:0]
	for _, dir := range dirs {
		if dir != "" && IsShim(filepath.Join(dir, "tmux")) {
			continue
		}
		keep = append(keep, dir)
	}
	return strings.Join(keep, string(filepath.ListSeparator))
}

// WithoutShims returns env with its PATH cleaned (CleanPath).
func WithoutShims(env []string) []string {
	out := slices.Clone(env)
	for i, kv := range out {
		if v, ok := strings.CutPrefix(kv, "PATH="); ok {
			out[i] = "PATH=" + CleanPath(v)
		}
	}
	return out
}
