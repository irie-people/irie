package tmux

import (
	"fmt"
	"strings"
)

// ConfOptions are the config values the generated tmux.conf uses.
type ConfOptions struct {
	FocusKey     string // ui.focus_key
	SidebarWidth int    // ui.sidebar_width
	FlipKey      string // ui.flip_key; "" binds none
	Bin          string // the irie binary the flip key runs
}

// Conf returns the generated tmux.conf (DESIGN §2.3). The server reads only
// this file, never the user's own tmux.conf.
func Conf(o ConfOptions) string {
	return fmt.Sprintf(`# Generated by Irie; changes are overwritten.

# The sidebar is the status line, and there are no stray tmux commands.
set -g status off
set -g prefix None

# Toggle focus between the sidebar and the slot. While the Mac app zooms the
# slot it has no sidebar, so the key goes to the agent.
bind -n '%[1]s' if -F '#{window_zoomed_flag}' 'send-keys %[1]s' "if -F '#{==:#{pane_index},0}' 'select-pane -t %[2]s' 'select-pane -t %[3]s'"

# Click to focus, wheel to scroll.
set -g mouse on

# %[3]s is always the sidebar and %[2]s always the slot.
set -g base-index 0
set -gw pane-base-index 0

# A dead agent keeps its exit status and last screen.
set -gw remain-on-exit on
set -g history-limit 50000

# What Claude Code's terminal docs ask for (Shift+Enter, progress). The
# fixed index keeps a reload of this file from adding the feature twice.
set -gw allow-passthrough on
set -s focus-events on
set -s extended-keys on
set -s terminal-features[90] 'xterm*:extkeys'

# The terminal window title, used to find the Irie window.
set -g set-titles on
set -g set-titles-string Irie

# Esc reaches agents promptly.
set -s escape-time 10

# irie:0 follows the latest client. Agent windows are sized to the slot.
set -gw window-size latest

# Keep the sidebar's width when a client resizes the window. Resizing a pane
# would end the Mac app's zoom, so while irie:0 is zoomed it is left alone.
# The hook fires for every window, an agent's included, so it asks irie:0.
set-hook -g window-resized "if -F -t %[2]s '#{window_zoomed_flag}' '' 'resize-pane -t %[3]s -x %[4]d'"
`, o.FocusKey, Slot, Sidebar, o.SidebarWidth) + flipBinding(o)
}

// TeamSocket is the socket name of the team server beside the server named
// socket (DESIGN §2.3).
func TeamSocket(socket string) string { return socket + "-teams" }

// TeamConf returns the team server's generated tmux.conf. Claude Code's
// agent teams open their teammates' panes there, and the Mac app shows each
// beside its session; the options are the main server's, so a teammate
// runs as an agent does. The anchors are dead panes that stay, and the
// server stays up with no session.
func TeamConf() string {
	return `# Generated by Irie; changes are overwritten.

set -g status off
set -g prefix None
set -g mouse on
set -g base-index 0
set -gw pane-base-index 0
set -gw remain-on-exit on
set -g history-limit 50000
set -gw allow-passthrough on
set -s focus-events on
set -s extended-keys on
set -s terminal-features[90] 'xterm*:extkeys'
set -s escape-time 10
set -s exit-empty off
set -gw window-size latest
`
}

// flipBinding binds ui.flip_key to `irie ctl flip`, which turns the slot
// between the shown session's conversation and its raw terminal (DESIGN
// §4.7). While the Mac app zooms the slot, the app has its own flip, so the
// key goes to the agent. A binary path that quoting cannot carry binds
// nothing.
func flipBinding(o ConfOptions) string {
	if o.FlipKey == "" || o.Bin == "" || strings.ContainsAny(o.Bin, "'\"\\$`\n{}") {
		return ""
	}
	return fmt.Sprintf(`
# Flip the slot between the shown session's conversation and its terminal.
bind -n '%[1]s' if -F '#{window_zoomed_flag}' { send-keys '%[1]s' } { run-shell -b '"%[2]s" ctl flip' }
`, o.FlipKey, o.Bin)
}
