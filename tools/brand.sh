#!/bin/sh
# Prints the product's names from internal/brand/brand.go, the one place
# they are kept (DESIGN §2.10), for the scripts that build and install it.
#
#   eval "$(tools/brand.sh)"   sets BRAND_NAME, BRAND_SLUG, BRAND_ENV,
#                              BRAND_BUNDLE_ID, BRAND_SITE, BRAND_REPO,
#                              BRAND_TAGLINE, BRAND_BAR and BRAND_EXE (the
#                              Mac app's executable)
#   tools/brand.sh --swift     prints mac/Sources/Irie/Brand.swift
set -eu
root=$(cd "$(dirname "$0")/.." && pwd)
src=$root/internal/brand/brand.go

# get KEY is the string constant KEY's value in brand.go.
get() {
	v=$(sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*\"\([^\"]*\)\".*/\1/p" "$src" | head -n 1)
	if [ -z "$v" ]; then
		echo "brand.sh: $src has no $1" >&2
		exit 1
	fi
	printf '%s' "$v"
}
name=$(get Name)
slug=$(get Slug)
bundle=$(get BundleID)
site=$(get Site)
repo=$(get Repo)
env=$(get EnvPrefix)
tagline=$(get Tagline)
bar=$(get Bar)
# The Mac app's executable, as brand.Exe makes it: Name's ASCII letters and
# digits, 15 at most, or Slug's.
exe=$(printf '%s' "$name" | LC_ALL=C tr -cd 'A-Za-z0-9' | cut -c1-15)
[ -n "$exe" ] || exe=$(printf '%s' "$slug" | LC_ALL=C tr -cd 'a-z0-9' | cut -c1-15)

case ${1:-} in
"")
	# Single quotes, with any ' in a value closed, escaped and reopened.
	q() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
	echo "BRAND_NAME=$(q "$name")"
	echo "BRAND_SLUG=$(q "$slug")"
	echo "BRAND_ENV=$(q "$env")"
	echo "BRAND_BUNDLE_ID=$(q "$bundle")"
	echo "BRAND_SITE=$(q "$site")"
	echo "BRAND_REPO=$(q "$repo")"
	echo "BRAND_TAGLINE=$(q "$tagline")"
	echo "BRAND_BAR=$(q "$bar")"
	echo "BRAND_EXE=$(q "$exe")"
	;;
--swift)
	# Swift string literals: \ and " escaped.
	s() { printf '"%s"' "$(printf '%s' "$1" | sed 's/[\\"]/\\&/g')"; }
	cat <<EOF
// Generated by tools/brand.sh --swift from internal/brand/brand.go, the one
// place the product's names are kept (DESIGN §2.10). Edit that file, not
// this one, then run tools/brand.sh --swift >mac/Sources/Irie/Brand.swift.

/// The product's names, as internal/brand has them.
enum Brand {
    /// The product's name as a person reads it.
    static let name = $(s "$name")
    /// Its name for computers: the command, its folders and its socket's.
    static let slug = $(s "$slug")
    /// The start of its environment variables' names.
    static let envPrefix = $(s "$env")
    /// The app's bundle identifier.
    static let bundleID = $(s "$bundle")
    /// The guide's address, ending in a slash.
    static let site = $(s "$site")
    /// The source's address.
    static let repo = $(s "$repo")
    /// The line under the name on the welcome.
    static let tagline = $(s "$tagline")

    /// The environment variable called name, such as env("CORE_SOCKET").
    static func env(_ name: String) -> String { envPrefix + "_" + name }
}
EOF
	;;
*)
	echo "usage: tools/brand.sh [--swift]" >&2
	exit 2
	;;
esac
